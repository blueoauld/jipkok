CREATE EXTENSION IF NOT EXISTS postgis WITH SCHEMA public;

CREATE TABLE access_reward
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    phone_number VARCHAR(11)                             NOT NULL,
    member_id    BIGINT                                  NOT NULL,
    platform     VARCHAR(255)                            NOT NULL,
    device_name  VARCHAR(100),
    ip_address   VARCHAR(45)                             NOT NULL,
    accessed_on  date                                    NOT NULL,
    CONSTRAINT pk_access_reward PRIMARY KEY (id)
);

CREATE TABLE ad_reward
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    transaction_id VARCHAR(64)                             NOT NULL,
    phone_number   VARCHAR(11)                             NOT NULL,
    member_id      BIGINT                                  NOT NULL,
    rewarded_on    date                                    NOT NULL,
    CONSTRAINT pk_ad_reward PRIMARY KEY (id)
);

CREATE TABLE attendance
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    phone_number VARCHAR(11)                             NOT NULL,
    member_id    BIGINT                                  NOT NULL,
    attended_on  date                                    NOT NULL,
    CONSTRAINT pk_attendance PRIMARY KEY (id)
);

CREATE TABLE chat_message
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE             NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE             NOT NULL,
    room_id    BIGINT                                  NOT NULL,
    sender_id  BIGINT                                  NOT NULL,
    type       VARCHAR(255)                            NOT NULL,
    content    VARCHAR(1000),
    object_key VARCHAR(255),
    CONSTRAINT pk_chat_message PRIMARY KEY (id)
);

CREATE TABLE chat_room
(
    deleted_at      TIMESTAMP(6) WITH TIME ZONE,
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at      TIMESTAMP(6) WITH TIME ZONE             NOT NULL,
    updated_at      TIMESTAMP(6) WITH TIME ZONE             NOT NULL,
    low_member_id   BIGINT                                  NOT NULL,
    high_member_id  BIGINT                                  NOT NULL,
    last_message_id BIGINT                                  NOT NULL,
    CONSTRAINT pk_chat_room PRIMARY KEY (id)
);

CREATE TABLE chat_room_member
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at           TIMESTAMP(6) WITH TIME ZONE             NOT NULL,
    updated_at           TIMESTAMP(6) WITH TIME ZONE             NOT NULL,
    room_id              BIGINT                                  NOT NULL,
    member_id            BIGINT                                  NOT NULL,
    last_read_message_id BIGINT                                  NOT NULL,
    unread_count         INTEGER                                 NOT NULL,
    CONSTRAINT pk_chat_room_member PRIMARY KEY (id)
);

CREATE TABLE device_token
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE             NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE             NOT NULL,
    member_id  BIGINT                                  NOT NULL,
    token      VARCHAR(255)                            NOT NULL,
    platform   VARCHAR(255)                            NOT NULL,
    CONSTRAINT pk_device_token PRIMARY KEY (id)
);

CREATE TABLE feed_post
(
    deleted_at TIMESTAMP(6) WITH TIME ZONE,
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE             NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE             NOT NULL,
