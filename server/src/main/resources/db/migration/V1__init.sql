CREATE TABLE feed_post_report
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE             NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE             NOT NULL,
    reporter_id BIGINT                                  NOT NULL,
    post_id     BIGINT                                  NOT NULL,
    CONSTRAINT pk_feed_post_report PRIMARY KEY (id)
);

CREATE TABLE member
(
    deleted_at                TIMESTAMP(6) WITH TIME ZONE,
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at                TIMESTAMP(6) WITH TIME ZONE             NOT NULL,
    updated_at                TIMESTAMP(6) WITH TIME ZONE             NOT NULL,
    phone_number              VARCHAR(11)                             NOT NULL,
    password                  VARCHAR(255)                            NOT NULL,
    gender                    VARCHAR(255)                            NOT NULL,
    nickname                  VARCHAR(10)                             NOT NULL,
    birth_year                INTEGER                                 NOT NULL,
    comment                   VARCHAR(100),
    bio                       VARCHAR(1000),
    role                      VARCHAR(255)                            NOT NULL,
    latitude                  DOUBLE PRECISION,
    longitude                 DOUBLE PRECISION,
    located_at                TIMESTAMP(6) WITH TIME ZONE,
    received_like_count       INTEGER                                 NOT NULL,
    point_balance             INTEGER                                 NOT NULL,
    note_receive_enabled      BOOLEAN                                 NOT NULL,
    feed_notification_enabled BOOLEAN                                 NOT NULL,
    CONSTRAINT pk_member PRIMARY KEY (id)
);

CREATE TABLE member_block
